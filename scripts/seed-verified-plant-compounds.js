async function seed() {
  const pool = mysql.createPool({
    host: process.env.DB_HOST || "localhost",
    port: process.env.DB_PORT ? parseInt(process.env.DB_PORT, 10) : 3306,
    user: process.env.DB_USER || "root",
    password: process.env.DB_PASSWORD ?? "",
    database: process.env.DB_NAME || "natureaide_db",
  });

  console.log(`Seeding ${VERIFIED_PHYTOCHEMICALS.length} verified phytochemicals...`);

  for (const comp of VERIFIED_PHYTOCHEMICALS) {
    const [existing] = await pool.query(
      `SELECT id FROM plant_compounds WHERE LOWER(plantScientificName) = LOWER(?) AND LOWER(compoundName) = LOWER(?)`,
      [comp.plantScientificName, comp.compoundName]
    );

    const refJson = JSON.stringify(comp.references || []);

    if (existing.length === 0) {
      await pool.query(
        `
        INSERT INTO plant_compounds (
          plantId, plantScientificName, plantCommonName, compoundName,
          iupacName, molecularFormula, molecularWeight, compoundClass,
          pubchemId, smiles, plantPartReported, referencesData, verificationStatus
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'VERIFIED_DATABASE')
        `,
        [
          comp.plantId,
          comp.plantScientificName,
          comp.plantCommonName,
          comp.compoundName,
          comp.iupacName || null,
          comp.molecularFormula,
          comp.molecularWeight,
          comp.compoundClass,
          comp.pubchemId,
          comp.smiles,
          comp.plantPartReported || null,
          refJson,
        ]
      );
      console.log(`Inserted: ${comp.compoundName} for ${comp.plantCommonName}`);
    } else {
      await pool.query(
        `
        UPDATE plant_compounds SET
          plantId = ?,
          plantCommonName = ?,
          iupacName = ?,
          molecularFormula = ?,
          molecularWeight = ?,
          compoundClass = ?,
          pubchemId = ?,
          smiles = ?,
          plantPartReported = ?,
          referencesData = ?,
          verificationStatus = 'VERIFIED_DATABASE'
        WHERE id = ?
        `,
        [
          comp.plantId,
          comp.plantCommonName,
          comp.iupacName || null,
          comp.molecularFormula,
          comp.molecularWeight,
          comp.compoundClass,
          comp.pubchemId,
          comp.smiles,
          comp.plantPartReported || null,
          refJson,
          existing[0].id,
        ]
      );
      console.log(`Updated: ${comp.compoundName} for ${comp.plantCommonName}`);
    }
  }

  const [countRows] = await pool.query("SELECT COUNT(*) as count FROM plant_compounds");
  console.log(`Seeding complete. Total compounds in plant_compounds: ${countRows[0].count}`);
  await pool.end();
}

seed().catch((err) => {
  console.error("Seed error:", err);
  process.exit(1);
});

